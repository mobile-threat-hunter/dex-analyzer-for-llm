#!/usr/bin/env python3
"""Regenerate ``native/core_ext/sdk_member_classes.inc`` (dexllm#127).

The Java view spells a member class with ``.`` only where nesting is PROVEN.
For a class a loaded dex declares, the proof is its own ``InnerClass`` +
``EnclosingClass`` annotations. A framework class is declared in no loaded
dex, so its proof is the SDK catalog: ``sdk_classes`` in the bundled
``component_bases.json`` was derived from dotted AOSP names, and a ``$`` there
is a nesting separator exactly when the prefix before it is itself an SDK
class (see ``scripts/gen_component_data.py``).

The C++ adapter cannot read Python package data, so the pairs are compiled in.
``tests/test_member_class_spelling.py`` checks that this file is what the
script produces from the committed JSON.

Usage:
    python scripts/gen_sdk_member_classes.py [output.inc]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src/dexllm/data/component_bases.json"
OUT = ROOT / "native/core_ext/sdk_member_classes.inc"


def pairs(sdk: set[str]) -> list[tuple[str, str]]:
    out = []
    for d in sdk:
        if "$" not in d:
            continue
        cut = d.rindex("$")
        if d[:cut] + ";" in sdk:
            out.append((d, d[cut + 1 : -1]))
    return sorted(out)


def render(sdk: set[str]) -> str:
    lines = [
        "// GENERATED by scripts/gen_sdk_member_classes.py from",
        "// src/dexllm/data/component_bases.json -- do not edit by hand.",
        "// (descriptor, Java simple name) of every SDK member class, sorted.",
    ]
    for d, n in pairs(sdk):
        lines.append(f'{{"{d}", "{n}"}},')
    return "\n".join(lines) + "\n"


def main() -> None:
    sdk = set(json.loads(DATA.read_text())["sdk_classes"])
    if len(sys.argv) > 2 or (len(sys.argv) == 2 and sys.argv[1].startswith("-")):
        sys.exit(__doc__)
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.write_text(render(sdk))


if __name__ == "__main__":
    main()

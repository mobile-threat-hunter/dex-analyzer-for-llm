_UBIQUITOUS = (
    "->startActivity(",
    "->startActivities(",
    "->startActivityForResult(",
    "->sendBroadcast(",
    "->sendOrderedBroadcast(",
    "->bindService(",
    "->getSystemService(",
    "Landroid/content/ContentResolver;->query(",
    "Landroid/content/pm/PackageManager;->getPackageInfo(",
    "Landroid/app/NotificationManager;->notify(",
    # the reflection MECHANICS, as opposed to the intent-expressing steps that ARE
    # listed (forName / invoke / setAccessible / loadClass): including these tripled
    # REFLECTION on the corpus while identifying no app the kept entries do not.
    "Ljava/lang/Class;->getDeclaredMethod(",
    "Ljava/lang/Class;->getMethod(",
    "Ljava/lang/Class;->getDeclaredField(",
    "Ljava/lang/Class;->newInstance(",
    "Ljava/lang/reflect/Field;->get(",
    "Ljava/lang/reflect/Field;->set(",
)



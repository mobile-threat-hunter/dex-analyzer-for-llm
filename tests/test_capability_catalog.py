# --- dexllm#30: the catalog is generated, and the selection is a decision ------
#
# The enrichment moved the catalog from 50 hand-typed entries to 276 generated from
# a curated (class, member) selection. Three things now have to be guarded that a
# schema check cannot see: that the committed file still IS what the generator
# produces, that every key names a real AOSP member (a typo matches nothing and
# raises nothing — the dexllm#36 defect), and that the two selection rules the
# measurements forced are not quietly reversed by a later bulk load.

_GENERATOR = (
    pathlib.Path(__file__).resolve().parents[1]
    / "scripts"
    / "gen_capability_catalog.py"
)

# APIs excluded BY MEASUREMENT, not by taste. Most were top additions of the
# rejected full projection (`startActivity` / `query` / `startActivityForResult` in
# 16 of the 32 corpus sources each); the reflection mechanics and
# `NotificationManager.notify` carry no `@RequiresPermission` at all and so could
# never arrive that way — they are here because they are equally ubiquitous and the
# rule has to be one rule. The exhaustive permission surface is
# `dangerous_permission_apis`, which has all 5,150.
# Matched on the MEMBER part, not on a full key prefix: the catalog's own rule is
# that a key names the class the APP writes, so `Landroid/app/Activity;->startActivity`
